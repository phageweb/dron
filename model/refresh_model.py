#!/usr/bin/env python3
"""Export the default geometry, derive mass properties and verify fit/balance.

Requires OpenSCAD on PATH and Python's standard library. No external packages.
Empty intersection is success only with exit 1, the expected message and no
OpenSCAD errors/warnings. Other errors must never masquerade as clearance.
"""
from pathlib import Path
from tempfile import TemporaryDirectory
import hashlib
import json
import math
import re
import subprocess

from check_meshes import inspect

ROOT = Path(__file__).resolve().parent
FILES = (("base", "1-base.stl"), ("insert", "2-camera_insert.stl"),
         ("lidar", "3-d500_module.stl"))


def scad(source, output, definitions=(), empty=False):
    command = ["openscad", "-o", str(output)]
    if output.suffix == ".stl":
        command.extend(["--export-format", "asciistl"])
    for definition in definitions:
        command.extend(["-D", definition])
    command.append(str(ROOT / source))
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    log = result.stdout + result.stderr
    expected = result.returncode == (1 if empty else 0)
    if empty:
        expected = expected and "Current top level object is empty." in log
    if not expected or "ERROR:" in log or "WARNING:" in log:
        raise RuntimeError(f"{command}\n{log}")
    return log


def echo(log, name):
    match = re.search(r"^ECHO: " + re.escape(name) + r" = (.+)$", log, re.M)
    if not match:
        raise RuntimeError(f"Missing {name} output")
    return json.loads(match[1])


def balance(log):
    values = echo(log, "balance")
    items = echo(log, "mass_items")
    names = echo(log, "mass_names")
    assert len(names) == len(items)
    # Independent arithmetic on the emitted item budget. OpenSCAD prints about
    # six significant digits, so tolerances allow that serialization rounding.
    mass = sum(item[0] for item in items)
    cg = [sum(item[0]*item[axis] for item in items)/mass for axis in (1, 2, 3)]
    assert math.isclose(mass, values[0], abs_tol=0.002)
    assert all(math.isclose(a, b, abs_tol=0.001) for a, b in zip(cg, values[1:4]))
    battery = items[-1]
    targets = [-sum(item[0]*item[axis] for item in items[:-1])/battery[0] for axis in (1, 2)]
    assert all(math.isclose(a, b, abs_tol=0.001) for a, b in zip(targets, values[6:8]))
    return dict(mass_g=values[0], cg_mm=values[1:4], battery_xy_mm=values[4:6],
                battery_target_xy_mm=values[6:8],
                cg_with_centered_battery_mm=[-targets[0]*battery[0]/mass,
                                             -targets[1]*battery[0]/mass, cg[2]],
                items=[dict(name=n, mass_g=p[0], cg_mm=p[1:]) for n, p in zip(names, items)],
                independent_arithmetic_pass=True)


def main():
    with TemporaryDirectory(prefix="pavo-refresh-") as temporary:
        work = Path(temporary)
        meshes = []
        for part, filename in FILES:
            target = work / filename
            scad("pavo20_pro_assembly.scad", target, [f'part="{part}"'])
            report = inspect(target)
            report["file"] = filename
            meshes.append(report)
        # Only install successfully exported, closed, connected meshes.
        for _, filename in FILES:
            (ROOT / filename).write_bytes((work / filename).read_bytes())
        (ROOT / "mesh_report.json").write_text(json.dumps(meshes, indent=2) + "\n")
        properties = ["// Generated by refresh_model.py; do not edit. STL print coordinates."]
        for (part, _), mesh in zip(FILES, meshes):
            properties += [f'{part}_volume_mm3 = {mesh["volume_mm3"]};',
                           f'{part}_print_cg = {json.dumps(mesh["centroid_mm"])};']
        (ROOT / "print_mass_properties.scad").write_text("\n".join(properties) + "\n")

        checks, budgets = [], []
        for battery in ("750", "550"):
            for lidar in (False, True):
                for angle in (0, 20, 40):
                    definitions = ['part="check"', f'battery_variant="{battery}"',
                                   f'lidar_enabled={str(lidar).lower()}', f'camera_angle={angle}']
                    log = scad("check_clearances.scad", work / "clearance.stl", definitions, empty=True)
                    checked_budget = balance(log)
                    assert all(abs(v) < 0.001 for v in checked_budget["cg_mm"][:2])
                    checks.append(dict(battery=battery, lidar=lidar, angle=angle, pass_empty=True))
                    if angle == 20:
                        budgets.append(dict(battery=battery, lidar=lidar, **checked_budget))
        for case in ("frame_heads_bridge", "gps_base", "gps_antenna", "gps_cable_base"):
            scad("audit_mounting.scad", work / "audit.stl",
                 ['part="check"', f'audit_case="{case}"'], empty=True)
            checks.append(dict(case=case, uses_exported_stl=True, pass_empty=True))
        # Deliberate regressions must produce nonzero-volume collision geometry.
        for name, setting in (("rotor", "propeller_z=1"),
                              ("old_bridge_pitch", "lidar_dock_y=36"),
                              ("old_gps_position", "gps_y=42")):
            target = work / f"negative-{name}.stl"
            scad("check_clearances.scad", target, ['part="check"', setting])
            vertices = [tuple(map(float, line.split()[1:])) for line in target.read_text().splitlines()
                        if line.strip().startswith("vertex ")]
            volume = 0
            for i in range(0, len(vertices), 3):
                a, b, c = vertices[i:i+3]
                volume += (a[0]*(b[1]*c[2]-b[2]*c[1]) + a[1]*(b[2]*c[0]-b[0]*c[2])
                           + a[2]*(b[0]*c[1]-b[1]*c[0]))/6
            assert volume > 0.001, (name, volume)
            checks.append(dict(case=name, negative_control_detects_collision=True, volume_mm3=volume))

        # A centered battery must expose the residual moment instead of a forced zero.
        manual = balance(scad("pavo20_pro_assembly.scad", work / "manual.csg",
                              ['part="check"', "auto_balance_battery=false"]))
        assert abs(manual["cg_mm"][1]) > 0.1
        checks.append(dict(case="manual_centered_battery", balance=manual))
        # Verify rotation and the print-to-assembly inverse transform independently.
        for angle in (0, 40):
            result = balance(scad("pavo20_pro_assembly.scad", work / "angle.csg",
                                  ['part="check"', f"camera_angle={angle}"]))
            by_name = {item["name"]: item for item in result["items"]}
            camera = by_name["camera"]["cg_mm"]
            assert math.isclose(camera[1], -32-3*math.cos(math.radians(angle)), abs_tol=0.001)
            assert math.isclose(camera[2], 14+3*math.sin(math.radians(angle)), abs_tol=0.001)
            bridge = by_name["D500_bridge"]["cg_mm"]
            expected = [meshes[2]["centroid_mm"][0], -meshes[2]["centroid_mm"][1],
                        25-meshes[2]["centroid_mm"][2]]
            assert all(math.isclose(a,b,abs_tol=0.001) for a,b in zip(bridge,expected))
        checks.append(dict(case="camera_and_bridge_transforms", passed=True))
        (ROOT / "balance_report.json").write_text(json.dumps(budgets, indent=2) + "\n")
        hashes = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                  for name in [filename for _, filename in FILES] +
                  ["pavo20_pro_assembly.scad", "camera_insert.scad", "print_mass_properties.scad"]}
        (ROOT / "audit_report.json").write_text(json.dumps(dict(sha256=hashes, checks=checks), indent=2) + "\n")
        (ROOT / "clearance_report.txt").write_text(
            "PASS: 12 battery/lidar/camera configurations including GPS, reserved connector and frame heads.\n"
            "PASS: 4 regression checks against exported STL.\n"
            "PASS: old bridge pitch, old GPS position and raised rotor plane trigger volume collisions.\n"
            "PASS: independent mass/moment arithmetic, centered manual battery and camera/bridge transforms.\n"
            "Frame heads: diameter 4.2 mm, height 2 mm, additional radial clearance 0.4 mm.\n"
            "Coplanar carbon/head seating excludes only 0.02 mm; cable envelope is an estimate.\n"
            "No physical fit, strength, vibration or flight validation.\n")
        for row in budgets:
            print(f'{row["battery"]} lidar={row["lidar"]}: {row["mass_g"]:.3f} g; '
                  f'battery XY={row["battery_xy_mm"]}; CG={row["cg_mm"]}')
        print("Exports, STL properties, balance and clearance reports refreshed successfully.")


if __name__ == "__main__":
    main()
